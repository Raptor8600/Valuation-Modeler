"""Download tab: the workbook (written by the unchanged builder, with your overrides typed into its yellow cells),
the raw data snapshot and an audit pack."""	
import json	

import streamlit as st 

from valuation import app_model 
from valuation.builder_bridge import workbook_bytes, workbook_filename, parse_snapshot, builder_available 
from modules.state import basis_badge 
__build__ = "2ce234981780815f" 


def render(snapshot, res):	
    basis_badge(res) 
    settings, ov, switches = st.session_state.get("_current", ({}, {}, {})) 
    xo = app_model.workbook_overrides(settings, ov, switches) 
    basis = res.settings["in_Basis"]	
    if not builder_available(): 
        st.info("Excel workbooks are generated privately by the owner and are not available in the hosted app.")	
    st.markdown(f"The workbook is generated by the original (private) builder on the " 
                f"**{basis}** basis from the same data snapshot, then every change you made here is typed into the matching "	
                f"workbook cell. Excel recalculates on open and should show the same results (tested to 0.1%).")	
    changed = {k: v for k, v in xo.items() if k not in settings}	
    if changed: 
        st.markdown("Overrides written into the workbook:") 
        st.json(changed) 
    if builder_available() and st.button(f"Build {basis} workbook"): 
        with st.spinner("Writing workbook…"): 
            data = workbook_bytes(snapshot, basis, xo) 
        st.download_button("Download .xlsx", data, file_name=workbook_filename(parse_snapshot(snapshot, basis)), 
                           mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")	
    st.download_button("Download the raw data snapshot (JSON)", json.dumps(snapshot), file_name= 
                       f"{snapshot['_meta']['ticker']}_snapshot.json", mime="application/json")	
    st.download_button("Download the audit pack (every input, its source tag and the results)", app_model.audit_pack(res),	
                       file_name=f"{res.company.ticker}_{basis}_audit.json", mime="application/json") 
